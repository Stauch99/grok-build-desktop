const TABLES: Record<Locale, Record<string, string>> = { zh: ZH, en: EN };

export const LOCALE_CHOICES: ReadonlyArray<{ id: Locale; native: string }> = [
  { id: "zh", native: "简体中文" },
  { id: "en", native: "English" },
];

export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let out = TABLES[locale][key] ?? TABLES.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

export function localeSearchHay(key: string, extra = ""): string {
  return `${t("zh", key)} ${t("en", key)} ${extra}`.replace(/\s+/g, " ").trim();
}

export function normalizeLocale(raw: unknown): Locale {
  return raw === "en" ? "en" : "zh";
}

export function fallbackCopy(locale: Locale): { title: string; retry: string; copy: string } {
  return {
    title: t(locale, "error.title"),
    retry: t(locale, "error.retry"),
    copy: t(locale, "error.copy"),
  };
}

function normalizeTrustPath(path: string): string {
  const trimmed = path.replace(/\\/g, "/").replace(/\/+$/, "");
  return trimmed || "/";
}

/** `/`, `$HOME`, `$HOME/Desktop`, `$HOME/Downloads` need extra trust copy. */
export function isDangerousTrustPath(path: string, home = ""): boolean {
  const n = normalizeTrustPath(path);
  if (n === "/") return true;
  const inferred = n.match(/^(\/(?:Users|home)\/[^/]+)/)?.[1] ?? "";
  const homes = [home, inferred].filter(Boolean).map(normalizeTrustPath);
  return homes.some((h) => n === h || n === `${h}/Desktop` || n === `${h}/Downloads`);
}
